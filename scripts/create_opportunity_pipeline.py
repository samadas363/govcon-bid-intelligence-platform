"""GovCon BD Intelligence Platform
Create opportunity pipeline and stage-history tables.

Uses the existing PostgreSQL connection.
Preserves existing business development data.
Safe to rerun when the tables already exist.
Explicitly commits successful database changes.
"""

import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parent.parent

if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.database import get_connection


CREATE_PIPELINE_TABLE = """
CREATE TABLE IF NOT EXISTS public.opportunity_pipeline (
    pipeline_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    opportunity_id BIGINT NOT NULL UNIQUE
        REFERENCES public.opportunities(opportunity_id)
        ON DELETE RESTRICT,

    pipeline_stage VARCHAR(40) NOT NULL DEFAULT 'New'
        CHECK (
            pipeline_stage IN (
                'New',
                'Screening',
                'Eligibility Check',
                'Bid/No-Bid Review',
                'Pursuing',
                'No-Bid',
                'Submitted',
                'Awarded',
                'Lost',
                'Closed'
            )
        ),

    bid_decision VARCHAR(30) NOT NULL DEFAULT 'Pending'
        CHECK (
            bid_decision IN (
                'Pending',
                'Bid',
                'No-Bid',
                'Conditional Bid'
            )
        ),

    decision_reason TEXT,
    decision_date DATE,

    pipeline_owner VARCHAR(150),
    next_action TEXT,
    follow_up_date DATE,

    priority VARCHAR(20) NOT NULL DEFAULT 'Medium'
        CHECK (
            priority IN ('Critical', 'High', 'Medium', 'Low')
        ),

    estimated_value NUMERIC(18, 2)
        CHECK (estimated_value IS NULL OR estimated_value >= 0),

    eligibility_status VARCHAR(30) NOT NULL DEFAULT 'Not Reviewed'
        CHECK (
            eligibility_status IN (
                'Not Reviewed',
                'Under Review',
                'Eligible',
                'Ineligible',
                'Requires Partner'
            )
        ),

    risk_level VARCHAR(20) NOT NULL DEFAULT 'Unassessed'
        CHECK (
            risk_level IN (
                'Unassessed',
                'Low',
                'Medium',
                'High',
                'Critical'
            )
        ),

    risk_notes TEXT,
    owner_notes TEXT,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
"""


CREATE_HISTORY_TABLE = """
CREATE TABLE IF NOT EXISTS public.opportunity_pipeline_history (
    history_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    pipeline_id BIGINT NOT NULL
        REFERENCES public.opportunity_pipeline(pipeline_id)
        ON DELETE RESTRICT,

    opportunity_id BIGINT NOT NULL
        REFERENCES public.opportunities(opportunity_id)
        ON DELETE RESTRICT,

    previous_stage VARCHAR(40),
    new_stage VARCHAR(40) NOT NULL,

    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by VARCHAR(150) NOT NULL DEFAULT CURRENT_USER,
    change_notes TEXT
);
"""


CREATE_INDEXES = [
    """
    CREATE INDEX IF NOT EXISTS idx_opportunity_pipeline_stage
    ON public.opportunity_pipeline(pipeline_stage);
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_opportunity_pipeline_follow_up
    ON public.opportunity_pipeline(follow_up_date);
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_opportunity_pipeline_priority
    ON public.opportunity_pipeline(priority);
    """,
    """
    CREATE INDEX IF NOT EXISTS idx_pipeline_history_opportunity
    ON public.opportunity_pipeline_history(
        opportunity_id,
        changed_at DESC
    );
    """,
]


CREATE_HISTORY_FUNCTION = """
CREATE OR REPLACE FUNCTION public.log_opportunity_pipeline_stage()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        INSERT INTO public.opportunity_pipeline_history (
            pipeline_id,
            opportunity_id,
            previous_stage,
            new_stage,
            change_notes
        )
        VALUES (
            NEW.pipeline_id,
            NEW.opportunity_id,
            NULL,
            NEW.pipeline_stage,
            'Initial pipeline stage'
        );

    ELSIF OLD.pipeline_stage IS DISTINCT FROM NEW.pipeline_stage THEN
        INSERT INTO public.opportunity_pipeline_history (
            pipeline_id,
            opportunity_id,
            previous_stage,
            new_stage,
            change_notes
        )
        VALUES (
            NEW.pipeline_id,
            NEW.opportunity_id,
            OLD.pipeline_stage,
            NEW.pipeline_stage,
            'Pipeline stage changed'
        );
    END IF;

    IF TG_OP = 'UPDATE' THEN
        NEW.updated_at = CURRENT_TIMESTAMP;
    END IF;

    RETURN NEW;
END;
$$;
"""


CREATE_HISTORY_TRIGGER = """
DROP TRIGGER IF EXISTS trg_opportunity_pipeline_stage_history
ON public.opportunity_pipeline;

CREATE TRIGGER trg_opportunity_pipeline_stage_history
AFTER INSERT OR UPDATE OF pipeline_stage
ON public.opportunity_pipeline
FOR EACH ROW
EXECUTE FUNCTION public.log_opportunity_pipeline_stage();
"""


def main():
    print("=" * 70)
    print("GOVCON BD — OPPORTUNITY PIPELINE MIGRATION")
    print("=" * 70)

    try:
        with get_connection() as connection:
            try:
                with connection.cursor() as cursor:
                    # 1. Create the pipeline table.
                    cursor.execute(CREATE_PIPELINE_TABLE)
                    print("[OK] Pipeline table created or already exists.")

                    # 2. Create the stage-history table.
                    cursor.execute(CREATE_HISTORY_TABLE)
                    print("[OK] Stage-history table created or already exists.")

                    # 3. Create indexes.
                    for statement in CREATE_INDEXES:
                        cursor.execute(statement)

                    print("[OK] Pipeline indexes created or verified.")

                    # 4. Install the history function and trigger.
                    cursor.execute(CREATE_HISTORY_FUNCTION)
                    cursor.execute(CREATE_HISTORY_TRIGGER)

                    print("[OK] Automatic stage-history trigger installed.")

                    # 5. Verify that the required tables exist.
                    cursor.execute(
                        """
                        SELECT table_name
                        FROM information_schema.tables
                        WHERE table_schema = 'public'
                          AND table_name IN (
                              'opportunity_pipeline',
                              'opportunity_pipeline_history'
                          )
                        ORDER BY table_name;
                        """
                    )

                    tables = [row[0] for row in cursor.fetchall()]

                    expected_tables = {
                        "opportunity_pipeline",
                        "opportunity_pipeline_history",
                    }

                    if set(tables) != expected_tables:
                        raise RuntimeError(
                            "Verification failed. Expected both pipeline "
                            f"tables, but found: {tables}"
                        )

                    # 6. Verify existing records and pipeline counts.
                    cursor.execute(
                        "SELECT COUNT(*) FROM public.opportunities;"
                    )
                    opportunity_count = cursor.fetchone()[0]

                    cursor.execute(
                        "SELECT COUNT(*) FROM public.opportunity_pipeline;"
                    )
                    pipeline_count = cursor.fetchone()[0]

                    cursor.execute(
                        "SELECT COUNT(*) "
                        "FROM public.opportunity_pipeline_history;"
                    )
                    history_count = cursor.fetchone()[0]

                    cursor.execute(
                        """
                        SELECT COUNT(*)
                        FROM public.opportunities
                        WHERE is_sample_data = TRUE;
                        """
                    )
                    sample_count = cursor.fetchone()[0]

                # CRITICAL FIX:
                # Persist all successful DDL changes before closing
                # the database connection.
                connection.commit()

                print("\n[OK] Database transaction committed successfully.")

            except Exception:
                connection.rollback()
                raise

        print("\nMIGRATION VERIFICATION")
        print("-" * 45)

        for table in tables:
            print(f"[OK] Table exists: public.{table}")

        print(f"Existing opportunities: {opportunity_count}")
        print(f"Sample opportunities:   {sample_count}")
        print(f"Pipeline entries:       {pipeline_count}")
        print(f"Stage history entries:  {history_count}")

        print("\nMIGRATION COMPLETED SUCCESSFULLY")
        print("Existing opportunities were not automatically added to the pipeline.")
        print("Existing opportunity records were not updated or deleted.")

    except Exception as exc:
        print(f"\nMIGRATION FAILED: {exc}")
        print("The migration transaction was rolled back if still uncommitted.")
        raise


if __name__ == "__main__":
    main()
